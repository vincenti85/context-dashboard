import { numbered } from "./format";

export interface TemplateContext {
  topic: string;
  target: string;
  coreMessage: string;
  pointsMd: string;
  tone: string;
  demo: string;
  cta: string;
  firstPoint: string;
  secondPoint: string;
  thirdPoint: string;
}

const DEFAULT_TITLES = (topic: string): string[] => [
  `${topic}, 처음부터 제대로 시작하는 법`,
  `${topic} 때문에 막혔다면 이 순서로 해보세요`,
  `${topic} 입문자가 가장 먼저 봐야 할 영상`,
  `${topic} 실습: 핵심만 따라 하기`,
  `${topic} 결과를 바꾸는 첫 설정`,
];

const DEFAULT_THUMBNAILS: string[] = [
  "처음엔 이것부터",
  "왜 결과가 흔들릴까?",
  "핵심만 따라하기",
  "첫 설정이 중요합니다",
  "바로 쓰는 방법",
];

export function buildBrief(ctx: TemplateContext): string {
  const { topic, target, coreMessage, pointsMd, tone, demo, cta } = ctx;
  return `# 콘텐츠 브리프: ${topic}

## 한 줄 주제

${topic}

## 타겟 시청자

${target}

## 시청자가 가진 문제

시청자는 "${topic}"에 관심이 있지만 어디서 시작해야 하는지, 무엇을 우선해야 하는지 명확히 알기 어렵다. 특히 관련 정보가 많아질수록 핵심 판단 기준을 놓치기 쉽다.

## 영상이 제공하는 약속

이 영상은 "${topic}"을 입문자도 따라 할 수 있는 순서로 정리하고, 바로 실행 가능한 기준과 예시를 제공한다.

## 핵심 메시지

${coreMessage}

## 다룰 포인트

${pointsMd}

## 피해야 할 방향

- 개념을 너무 넓게 확장하지 않는다.
- 전문 용어를 설명 없이 사용하지 않는다.
- 한 영상에서 모든 것을 해결하려고 하지 않는다.
- 시청자가 바로 따라 할 수 없는 추상적 조언으로 끝내지 않는다.

## 제작 가정

- 영상 길이는 8-10분이다.
- 설명 톤은 "${tone}"이다.
- 시연 또는 예시는 "${demo}"를 사용한다.
- CTA는 "${cta}"이다.
`;
}

export function buildOutline(ctx: TemplateContext): string {
  const { topic, target, coreMessage, cta, firstPoint, secondPoint, thirdPoint, demo } = ctx;
  return `# 영상 구성안: ${topic}

## 영상 기본 정보

- 예상 길이: 8-10분
- 타겟 시청자: ${target}
- 핵심 메시지: ${coreMessage}
- CTA: ${cta}

## 구성

| 구간 | 예상 시간 | 목적 | 말할 요지 | 화면 지시 | 시청자 감정 |
|---|---:|---|---|---|---|
| Hook | 0:00-0:30 | 문제 공감 | "${topic}"을 시작할 때 흔히 막히는 지점을 짚는다. | 나쁜 예시와 좋은 예시를 빠르게 대비한다. | 내 문제라고 느낀다. |
| 오프닝 | 0:30-1:00 | 기대 설정 | 오늘 영상에서 얻을 결과와 전체 흐름을 소개한다. | 영상 목차를 보여준다. | 볼 이유를 이해한다. |
| 문제 제기 | 1:00-2:30 | 기존 방식의 한계 설명 | 정보가 많거나 지침이 흐릴 때 결과 품질이 떨어지는 이유를 설명한다. | 오해와 진실 표를 보여준다. | 기존 방식의 한계를 이해한다. |
| 핵심 개념 | 2:30-4:00 | 기준 제시 | ${coreMessage} | 핵심 문장을 큰 자막으로 보여준다. | 판단 기준을 얻는다. |
| 실습 또는 예시 | 4:00-8:00 | 적용 방법 시연 | ${firstPoint}, ${secondPoint}, ${thirdPoint} 순서로 적용한다. | ${demo} | 따라 할 수 있다고 느낀다. |
| 정리 | 8:00-9:00 | 핵심 반복 | 오늘의 핵심을 3문장으로 정리한다. | 요약 카드 3개를 보여준다. | 기억할 내용을 정리한다. |
| CTA | 9:00-10:00 | 다음 행동 유도 | ${cta} | 다음 콘텐츠 제목 또는 실습 과제를 보여준다. | 다음 행동이 분명해진다. |

## 제목/썸네일 방향

- 제목은 "${topic}"을 통해 얻는 구체적 결과를 약속한다.
- 썸네일은 시청자가 겪는 문제를 짧게 보여준다.
- 입문자가 겁먹지 않도록 "첫 설정", "따라 하기", "실습" 같은 표현을 우선 사용한다.

## 대본 작성 시 주의점

- 타겟 시청자를 "${target}"으로 유지한다.
- 핵심 메시지를 "${coreMessage}" 하나로 모은다.
- 전문 용어는 짧게 정의한 뒤 사용한다.
- 설명보다 실제 적용 순서를 우선한다.
`;
}

export function buildUploadPackage(ctx: TemplateContext): string {
  const { topic, target, coreMessage, pointsMd, demo, cta } = ctx;
  const titles = DEFAULT_TITLES(topic);
  const thumbnails = DEFAULT_THUMBNAILS;

  return `# 업로드 패키지: ${topic}

## 1. 콘텐츠 브리프

이 영상은 "${topic}"을 주제로, ${target} 을/를 위한 실용적인 입문 콘텐츠다. 핵심 메시지는 "${coreMessage}"이다.

시청자는 복잡한 설명보다 바로 따라 할 수 있는 순서를 원한다. 이 패키지는 문제 공감, 핵심 개념, 실습 또는 예시, 업로드용 재활용 문안까지 한 번에 사용할 수 있게 구성한다.

## 2. 유튜브 제목 후보

${numbered(titles)}

## 3. 썸네일 문구 후보

${numbered(thumbnails)}

## 4. 영상 설명란

${topic} 을/를 시작하려고 했지만 어디서부터 해야 할지 막혔다면, 이번 영상에서 핵심 흐름을 정리해드립니다.

이번 영상에서 다루는 내용:

${pointsMd}

핵심 메시지:

${coreMessage}

${cta}

## 5. 고정 댓글

이번 영상의 핵심은 "${coreMessage}"입니다. 여러분이 적용해보고 싶은 상황이나 다음에 다뤘으면 하는 주제가 있다면 댓글로 남겨주세요.

## 6. 촬영용 대본

### Hook

${topic} 을/를 하려고 했는데, 생각보다 결과가 잘 안 나온 적 있으신가요?

분명히 정보를 넣었고, 설명도 했는데 결과가 애매하거나 매번 달라지는 경우가 있습니다.

오늘은 이 문제를 해결하기 위해 "${coreMessage}"라는 기준으로 전체 흐름을 정리해보겠습니다.

### 오프닝

이번 영상은 ${target} 을/를 위해 만들었습니다.

목표는 어렵게 설명하는 것이 아니라, 바로 따라 할 수 있는 순서로 "${topic}"을 정리하는 것입니다.

오늘은 세 가지를 중심으로 봅니다.

첫째, 왜 이 주제가 필요한지.

둘째, 어떤 순서로 접근해야 하는지.

셋째, 실제로 어떻게 적용하면 되는지입니다.

### 문제 제기

많은 분들이 처음에는 정보를 많이 넣으면 결과가 좋아질 거라고 생각합니다.

하지만 정보가 많아도 기준이 없으면 결과는 흔들립니다.

반대로 설명이 짧아도 역할, 목적, 출력 형식이 분명하면 훨씬 안정적인 결과를 얻을 수 있습니다.

그래서 이 영상에서는 "${topic}"을 단순 개념이 아니라 실제 작업 흐름으로 다룹니다.

### 핵심 개념

오늘의 핵심 메시지는 이것입니다.

${coreMessage}

이 문장을 기준으로 보면, 중요한 것은 더 많이 설명하는 것이 아니라 무엇을 기준으로 결과를 만들지 정하는 것입니다.

### 실습 또는 예시

이제 실제 적용 순서를 보겠습니다.

${pointsMd}

먼저 첫 번째 항목부터 확인합니다. 여기서는 시청자가 가장 자주 헷갈리는 지점을 짚고, 좋은 예와 나쁜 예를 나란히 보여줍니다.

다음으로 두 번째 항목을 적용합니다. 이때 설명만 하지 말고 화면에서 직접 파일, 설정, 문장 구조 또는 작업 결과를 보여줍니다.

마지막으로 전체 결과를 다시 확인합니다. 처음 요청 또는 초안과 최종 결과를 비교해서 무엇이 좋아졌는지 보여줍니다.

### 정리/CTA

오늘 내용은 세 문장으로 정리할 수 있습니다.

첫째, 결과가 흔들릴 때는 정보량보다 기준을 먼저 점검해야 합니다.

둘째, "${topic}"은 그 기준을 실제 작업에 적용하는 방법입니다.

셋째, ${coreMessage}

${cta}

## 7. 화면 구성 및 시연 지시

- Hook: 결과가 흔들리는 예시를 먼저 보여준다.
- 오프닝: 오늘 다룰 흐름을 3단계로 보여준다.
- 문제 제기: 정보량과 명확한 기준의 차이를 표로 보여준다.
- 핵심 개념: "${coreMessage}"를 큰 자막으로 보여준다.
- 실습: ${demo}
- 정리: 핵심 문장 3개와 CTA를 보여준다.

## 8. 챕터 타임라인

- 00:00 왜 결과가 흔들릴까?
- 00:30 오늘 영상에서 얻을 것
- 01:00 흔한 오해와 문제 상황
- 02:30 핵심 개념
- 04:00 실습 또는 예시
- 08:00 결과 비교와 정리
- 09:00 다음 행동 안내

## 9. 쇼츠 재가공 스크립트

### 쇼츠 1

${topic} 을/를 시작할 때 가장 흔한 실수는 정보를 많이 넣는 것만 신경 쓰는 겁니다.

하지만 결과를 바꾸는 건 정보량보다 기준입니다.

${coreMessage}

먼저 이 기준부터 잡아보세요.

### 쇼츠 2

결과가 매번 달라진다면 질문을 바꿔야 합니다.

"더 자세히 말해야 하나?"보다 먼저 볼 것은 "역할, 목적, 출력 형식이 분명한가?"입니다.

이 기준이 잡히면 "${topic}"도 훨씬 안정적으로 다룰 수 있습니다.

### 쇼츠 3

오늘의 핵심은 간단합니다.

${coreMessage}

복잡하게 시작하지 말고, 먼저 작은 예시 하나로 적용해보세요.

## 10. 쓰레드/X 게시글

${topic} 을/를 잘하려면 처음부터 모든 것을 완벽히 알 필요는 없습니다.

먼저 기준을 잡아야 합니다.

핵심은 이것입니다.

${coreMessage}

실제로는 다음 순서가 좋습니다.

${pointsMd}

정보를 더 넣기 전에, 결과가 어떤 기준으로 만들어져야 하는지 먼저 정하세요.

## 11. 인스타 캡션

${topic} 이 어렵게 느껴진다면 정보가 부족해서가 아닐 수 있습니다.

기준이 흐리면 결과도 흐려집니다.

오늘의 핵심은 "${coreMessage}"입니다.

작게 시작하고, 한 번에 하나씩 적용해보세요.

## 12. 다음 콘텐츠 아이디어

1. "${topic}" 다음 단계 실습
2. 좋은 예와 나쁜 예 비교 콘텐츠
3. 자주 하는 실수와 수정 방법

## 13. 품질 검토 체크리스트

- [x] Hook이 5초 안에 문제를 제시한다.
- [x] 타겟 시청자가 자신을 위한 영상이라고 느낄 수 있다.
- [x] 핵심 메시지가 하나로 모인다.
- [x] 설명이 비개발자에게 과하게 어렵지 않다.
- [x] 영상 제목과 썸네일 문구가 같은 약속을 전달한다.
- [x] 쇼츠와 SNS 문안이 본편과 연결된다.
- [x] CTA가 자연스럽고 구체적이다.
`;
}
